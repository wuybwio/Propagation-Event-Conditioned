from __future__ import annotations

from dataclasses import dataclass
import json
import math
import warnings
from pathlib import Path
from typing import Any

import numpy as np

from .building_heights import building_height


@dataclass(frozen=True)
class EnvironmentFeatureConfig:
    """Configuration for environment features.

    The proxy implementation is deliberately deterministic and auditable. Real
    DEM/building/land-use rasters can replace it without changing the tensor
    contract.
    """

    include_height: bool = False
    proxy_elevation_m: float = 100.0
    proxy_slope: float = 0.1
    proxy_relief: float = 0.0
    proxy_building_density: float = 0.2
    proxy_building_height_m: float = 8.0
    proxy_landuse_code: float = 1.0


@dataclass(frozen=True)
class OvertureBuildingConfig:
    """Controls conversion of Overture building tiles into raster features.

    The GeoJSON tiles generated by the Cesium helper retain ``height_source``.
    Heights produced by ``type_area_variation`` are intentionally represented as
    uncertain observations rather than treated as survey measurements.
    """

    tiles_dir: str | Path
    tile_size_deg: float = 0.1
    density_scale: float = 500.0
    height_scale_m: float = 50.0
    max_height_scale_m: float = 100.0
    quantile_bins_m: int = 401

    def __post_init__(self) -> None:
        if self.tile_size_deg <= 0 or self.density_scale <= 0:
            raise ValueError("tile_size_deg and density_scale must be positive")
        if self.height_scale_m <= 0 or self.max_height_scale_m <= 0:
            raise ValueError("height scales must be positive")
        if self.quantile_bins_m < 8:
            raise ValueError("quantile_bins_m must be at least 8")


def _validate_points(points: np.ndarray) -> np.ndarray:
    values = np.asarray(points, dtype=float)
    if values.ndim != 2 or values.shape[1] != 2:
        raise ValueError("points must have shape [n, 2] as longitude/latitude")
    if not np.isfinite(values).all():
        raise ValueError("points must contain finite coordinates")
    if np.any((values[:, 0] < -180) | (values[:, 0] > 180)):
        raise ValueError("longitude must be within [-180, 180]")
    if np.any((values[:, 1] < -90) | (values[:, 1] > 90)):
        raise ValueError("latitude must be within [-90, 90]")
    return values


def build_proxy_environment_features(
    points: np.ndarray,
    config: EnvironmentFeatureConfig,
    heights_m: np.ndarray | None = None,
) -> tuple[np.ndarray, dict[str, Any]]:
    """Return deterministic proxy features for points.

    Channel order is elevation, slope, relief, building density, building
    height and land-use code; height is appended when ``include_height`` is on.
    """

    values = _validate_points(points)
    count = len(values)
    base = np.tile(
        np.asarray(
            [
                config.proxy_elevation_m,
                config.proxy_slope,
                config.proxy_relief,
                config.proxy_building_density,
                config.proxy_building_height_m,
                config.proxy_landuse_code,
            ],
            dtype=float,
        ),
        (count, 1),
    )
    if not config.include_height:
        return base, {"feature_evidence": "proxy", "channel_order": "elevation,slope,relief,building_density,building_height,landuse"}
    if heights_m is None:
        raise ValueError("heights_m is required when include_height is enabled")
    heights = np.asarray(heights_m, dtype=float)
    if heights.shape != (count,) or not np.isfinite(heights).all() or np.any(heights <= 0):
        raise ValueError("heights_m must be a positive finite vector aligned with points")
    features = np.column_stack([base, heights])
    return features, {"feature_evidence": "proxy", "channel_order": "elevation,slope,relief,building_density,building_height,landuse,height_m"}


def _tile_indices(points: np.ndarray, tile_size_deg: float) -> set[tuple[int, int]]:
    """Return tiles containing requested points (not the enclosing bbox).

    Route points are sparse and often form a long diagonal. Selecting the
    enclosing rectangle would unnecessarily parse hundreds of unrelated
    Overture tiles, so selection is point-based and deterministic.
    """
    return {
        (
            math.floor(float(point[0]) / tile_size_deg),
            math.floor(float(point[1]) / tile_size_deg),
        )
        for point in points
    }


def _coordinate_pairs(value: Any) -> list[tuple[float, float]]:
    """Flatten GeoJSON coordinate arrays without requiring Shapely."""
    if isinstance(value, (list, tuple)):
        if len(value) >= 2 and isinstance(value[0], (int, float)) and isinstance(value[1], (int, float)):
            try:
                return [(float(value[0]), float(value[1]))]
            except (TypeError, ValueError):
                return []
        pairs: list[tuple[float, float]] = []
        for child in value:
            pairs.extend(_coordinate_pairs(child))
        return pairs
    return []


def _feature_centroid(feature: dict[str, Any]) -> tuple[float, float] | None:
    geometry = feature.get("geometry") or {}
    pairs = _coordinate_pairs(geometry.get("coordinates"))
    if not pairs:
        return None
    return (
        float(sum(pair[0] for pair in pairs) / len(pairs)),
        float(sum(pair[1] for pair in pairs) / len(pairs)),
    )


def _grid_index(value: float, axis: np.ndarray) -> int | None:
    if len(axis) > 1:
        tolerance = 0.51 * float(np.median(np.diff(axis)))
    else:
        tolerance = 0.01
    if value < float(axis.min()) - tolerance or value > float(axis.max()) + tolerance:
        return None
    index = int(np.abs(axis - value).argmin())
    return index


def build_overture_building_features(
    points: np.ndarray,
    config: OvertureBuildingConfig,
) -> tuple[np.ndarray, dict[str, Any]]:
    """Rasterize Overture building tiles into environment channels.

    Returned channels are ``density, mean_height, max_height, p90_height,
    estimated_fraction``. The legacy fifth channel now includes missing heights.
    Density includes height-missing footprints; height summaries exclude them.
    Metadata supplies raster-aligned missing/valid counts to disambiguate zero height
    placeholders. No physical height is imputed for unknown-only cells.
    """
    values = _validate_points(points)
    tiles_dir = Path(config.tiles_dir)
    if not tiles_dir.exists():
        raise FileNotFoundError(f"Overture tiles directory does not exist: {tiles_dir}")
    lon_axis = np.unique(np.round(values[:, 0], 9))
    lat_axis = np.unique(np.round(values[:, 1], 9))
    rows, cols = len(lat_axis), len(lon_axis)
    size = rows * cols
    counts = np.zeros(size, dtype=np.int64)
    valid_counts = np.zeros(size, dtype=np.int64)
    missing_counts = np.zeros(size, dtype=np.int64)
    estimated = np.zeros(size, dtype=np.int64)
    height_sum = np.zeros(size, dtype=np.float64)
    height_max = np.zeros(size, dtype=np.float32)
    # Do not allocate a dense [grid_cell, quantile_bin] matrix here.  A long
    # route can create a very large enclosing raster (millions of cells),
    # while only a small fraction of cells contain buildings.  The previous
    # dense matrix therefore caused multi-gigabyte allocations before any
    # propagation calculation started.  A sparse per-cell histogram preserves
    # the exact p90 calculation for occupied cells and has memory proportional
    # to the number of observed building heights.
    histogram: dict[int, dict[int, int]] = {}
    loaded_tiles = 0
    feature_count = 0
    source_counts: dict[str, int] = {}
    category_counts: dict[str, int] = {}
    axis_steps = [
        float(np.median(np.diff(axis)))
        for axis in (lon_axis, lat_axis)
        if len(axis) > 1
    ]
    coarse_grid = bool(axis_steps) and all(
        step >= config.tile_size_deg * 0.5 for step in axis_steps
    )

    for tile_x, tile_y in sorted(_tile_indices(values, config.tile_size_deg)):
        paths = sorted(tiles_dir.glob(f"tile_{tile_x}_{tile_y}*.geojson"))
        if not paths:
            continue
        for path in paths:
            try:
                payload = json.loads(path.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError):
                continue
            loaded_tiles += 1
            for feature in payload.get("features", []):
                properties = feature.get("properties") or {}
                geometry = feature.get("geometry") or {}
                if geometry.get("type") not in {"Polygon", "MultiPolygon"}:
                    continue
                centroid = _feature_centroid(feature)
                if centroid is None or not np.isfinite(centroid).all():
                    continue
                if coarse_grid:
                    lon, lat = tile_x * config.tile_size_deg, tile_y * config.tile_size_deg
                else:
                    lon, lat = centroid
                x = _grid_index(lon, lon_axis)
                y = _grid_index(lat, lat_axis)
                if x is None or y is None:
                    continue
                flat = y * cols + x
                counts[flat] += 1
                observation = building_height(properties)
                source = observation.source
                category = observation.category
                source_counts[source] = source_counts.get(source, 0) + 1
                category_counts[category] = category_counts.get(category, 0) + 1
                feature_count += 1
                height = observation.height_m
                if height is None:
                    missing_counts[flat] += 1
                    estimated[flat] += 1
                    continue
                valid_counts[flat] += 1
                height_sum[flat] += height
                height_max[flat] = max(height_max[flat], height)
                bin_index = min(config.quantile_bins_m - 1, max(0, int(round(height))))
                cell_histogram = histogram.setdefault(flat, {})
                cell_histogram[bin_index] = cell_histogram.get(bin_index, 0) + 1
                if category not in {"height_attribute", "floor_based"}:
                    estimated[flat] += 1

    mean_height = np.divide(height_sum, valid_counts, out=np.zeros_like(height_sum), where=valid_counts > 0)
    p90_height = np.zeros(size, dtype=np.float32)
    for index in np.flatnonzero(valid_counts):
        cell_histogram = histogram.get(int(index), {})
        if not cell_histogram:
            continue
        bins = np.fromiter(cell_histogram.keys(), dtype=np.int64)
        counts_for_bins = np.fromiter(cell_histogram.values(), dtype=np.int64)
        order = np.argsort(bins)
        cumulative = np.cumsum(counts_for_bins[order])
        target = int(math.ceil(0.9 * valid_counts[index]))
        p90_height[index] = float(bins[order][np.searchsorted(cumulative, target)])
    density = np.log1p(counts.astype(np.float32)) / math.log1p(config.density_scale)
    density = np.clip(density, 0.0, 1.0)
    mean_norm = np.clip(mean_height / config.height_scale_m, 0.0, 2.0) / 2.0
    max_norm = np.clip(height_max / config.max_height_scale_m, 0.0, 2.0) / 2.0
    p90_norm = np.clip(p90_height / config.max_height_scale_m, 0.0, 2.0) / 2.0
    estimated_fraction = np.divide(estimated, counts, out=np.zeros_like(mean_height), where=counts > 0)
    features = np.column_stack((density, mean_norm, max_norm, p90_norm, estimated_fraction)).astype(np.float32)
    missing_total = int(missing_counts.sum())
    if missing_total:
        warnings.warn(
            f"{missing_total} building records have missing height: footprints retained; "
            "height summaries exclude them (zero is a placeholder, not a real height). "
            "The uncertainty channel includes them; loss estimates remain heuristic, "
            "not measured 3-D obstruction.", RuntimeWarning, stacklevel=2,
        )
    metadata = {
        "feature_evidence": "Overture_building_tiles",
        "channel_order": "building_density_log,building_mean_height_norm,building_max_height_norm,building_p90_height_norm,building_estimated_fraction",
        "tiles_dir": str(tiles_dir),
        "loaded_tiles": loaded_tiles,
        "building_features": feature_count,
        "height_source_counts": source_counts,
        "height_category_counts": category_counts,
        "valid_height_features": int(valid_counts.sum()),
        "missing_height_features": missing_total,
        "feature_schema_version": 2,
        "height_quality_grid": {
            "alignment": "flattened latitude-major, longitude-minor raster (same as features)",
            "longitude": lon_axis.tolist(),
            "latitude": lat_axis.tolist(),
            "building_count": counts.tolist(),
            "valid_height_count": valid_counts.tolist(),
            "missing_height_count": missing_counts.tolist(),
        },
        "missing_height_policy": "retain footprint; no height imputation; zero summaries are placeholders",
        "estimated_height_note": "fifth channel includes estimated, unattributed and missing heights; height/num_floors are not proof of survey accuracy",
    }
    return features, metadata


def building_obstruction_loss_db(
    building_features: np.ndarray,
    *,
    max_loss_db: float = 18.0,
) -> np.ndarray:
    """Convert normalized building channels into a conservative loss prior."""
    values = np.asarray(building_features, dtype=float)
    if values.ndim != 2 or values.shape[1] < 5:
        raise ValueError("building_features must have at least five channels")
    if max_loss_db < 0:
        raise ValueError("max_loss_db must be non-negative")
    density, mean_height, max_height, p90_height, estimated = values[:, :5].T
    obstruction = 0.35 * density + 0.25 * mean_height + 0.25 * max_height + 0.15 * p90_height
    uncertainty_buffer = 0.15 * estimated
    return (max_loss_db * np.clip(obstruction + uncertainty_buffer, 0.0, 1.0)).astype(np.float32)


def station_path_obstruction_loss_db(
    points: np.ndarray,
    station_coordinates: np.ndarray,
    building_features: np.ndarray,
    axes: tuple[np.ndarray, np.ndarray],
    *,
    station_height_m: np.ndarray | float,
    flight_height_m: float,
    max_height_scale_m: float = 100.0,
    max_loss_db: float = 18.0,
    samples_per_km: float = 4.0,
    max_path_distance_km: float = 15.0,
) -> np.ndarray:
    """Estimate station-specific building obstruction along 3-D paths.

    ``building_features`` is the flattened raster returned by
    :func:`build_overture_building_features`.  The path is sampled in the
    horizontal plane and its interpolated ray height is compared with the
    building maximum-height channel.  This is an auditable approximation to
    ray/building intersection; it preserves a separate loss for every
    point/station pair instead of applying one scalar loss to all stations.
    """
    target = _validate_points(points)
    stations = _validate_points(station_coordinates)
    values = np.asarray(building_features, dtype=float)
    if values.ndim != 2 or values.shape[0] != len(np.unique(axes[0])) * len(np.unique(axes[1])) or values.shape[1] < 5:
        raise ValueError("building_features must be [len(lat_axis)*len(lon_axis), >=5]")
    lon_axis = np.asarray(axes[0], dtype=float)
    lat_axis = np.asarray(axes[1], dtype=float)
    if lon_axis.ndim != 1 or lat_axis.ndim != 1 or len(lon_axis) == 0 or len(lat_axis) == 0:
        raise ValueError("axes must contain non-empty longitude and latitude vectors")
    if (
        flight_height_m <= 0
        or max_height_scale_m <= 0
        or max_loss_db < 0
        or samples_per_km <= 0
        or max_path_distance_km <= 0
    ):
        raise ValueError("height, scales, max_loss_db, sampling and max_path_distance_km must be positive")
    station_heights = np.asarray(station_height_m, dtype=float)
    if station_heights.ndim == 0:
        station_heights = np.full(len(stations), float(station_heights))
    if station_heights.shape != (len(stations),) or not np.isfinite(station_heights).all():
        raise ValueError("station_height_m must be scalar or one value per station")

    # Path sampling calls the index lookup millions of times.  Overture grids
    # are regular, so use arithmetic indexing instead of an O(axis-length)
    # nearest-neighbour search for every sample (fall back to _grid_index for
    # the degenerate one-cell case).
    axis_steps = {
        "lon": float(np.median(np.diff(lon_axis))) if len(lon_axis) > 1 else None,
        "lat": float(np.median(np.diff(lat_axis))) if len(lat_axis) > 1 else None,
    }

    def grid_index(value: float, axis: np.ndarray, key: str) -> int | None:
        step = axis_steps[key]
        if step is None:
            return _grid_index(value, axis)
        index = int(round((value - float(axis[0])) / step))
        if index < 0 or index >= len(axis):
            return None
        if abs(float(axis[index]) - value) > 0.51 * abs(step):
            return None
        return index

    # ``build_overture_building_features`` normalizes height to
    # clip(height / (2 * max_height_scale_m), 0, 1). Undo that convention
    # before comparing a building with the interpolated flight ray height.
    max_height = np.clip(values[:, 2], 0.0, 1.0) * (2.0 * max_height_scale_m)
    estimated = np.clip(values[:, 4], 0.0, 1.0)
    rows, cols = len(lat_axis), len(lon_axis)
    result = np.zeros((len(target), len(stations)), dtype=np.float32)
    for point_index, (lon, lat) in enumerate(target):
        for station_index, (station_lon, station_lat) in enumerate(stations):
            dx_km = (lon - station_lon) * 111.32 * np.cos(np.radians((lat + station_lat) / 2.0))
            dy_km = (lat - station_lat) * 111.32
            distance_km = float(np.hypot(dx_km, dy_km))
            if distance_km > max_path_distance_km:
                continue
            count = max(2, int(np.ceil(distance_km * samples_per_km)) + 1)
            fractions = np.linspace(0.0, 1.0, count)
            max_excess = 0.0
            uncertainty = 0.0
            for fraction in fractions:
                sample_lon = station_lon + fraction * (lon - station_lon)
                sample_lat = station_lat + fraction * (lat - station_lat)
                x = grid_index(sample_lon, lon_axis, "lon")
                y = grid_index(sample_lat, lat_axis, "lat")
                if x is None or y is None:
                    continue
                flat = y * cols + x
                ray_height = station_heights[station_index] + fraction * (flight_height_m - station_heights[station_index])
                excess = max(0.0, max_height[flat] - ray_height)
                max_excess = max(max_excess, excess)
                uncertainty = max(uncertainty, estimated[flat])
            obstruction = max_excess / max_height_scale_m + 0.15 * uncertainty
            result[point_index, station_index] = max_loss_db * np.clip(obstruction, 0.0, 1.0)
    return result


def knife_edge_diffraction_loss_db(v: np.ndarray | float) -> np.ndarray:
    """Return single knife-edge diffraction loss for Fresnel parameter ``v``.

    The ITU-R approximation is zero for a clear path (``v <= -0.78``) and
    smoothly increases for an obstacle penetrating the first Fresnel zone.
    """
    values = np.asarray(v, dtype=float)
    loss = np.zeros_like(values)
    mask = values > -0.78
    shifted = values[mask] - 0.1
    loss[mask] = 6.9 + 20.0 * np.log10(
        np.sqrt(shifted * shifted + 1.0) + shifted
    )
    return np.clip(loss, 0.0, None)


def station_path_knife_edge_loss_db(
    points: np.ndarray,
    station_coordinates: np.ndarray,
    building_features: np.ndarray,
    axes: tuple[np.ndarray, np.ndarray],
    *,
    station_height_m: np.ndarray | float,
    flight_height_m: float,
    frequency_mhz: float,
    max_height_scale_m: float = 100.0,
    max_loss_db: float = 30.0,
    samples_per_km: float = 2.0,
    max_path_distance_km: float = 20.0,
    effective_earth_radius_factor: float = 4.0 / 3.0,
    estimated_height_buffer_m: float = 15.0,
    terrain_elevation_m: np.ndarray | None = None,
    station_ground_elevation_m: np.ndarray | float = 0.0,
    target_ground_elevation_m: np.ndarray | float | None = None,
) -> np.ndarray:
    """Estimate directional building diffraction loss for every link.

    Geometry (absolute heights above the same vertical datum):

    - transmitter: ``h_tx = station_ground + antenna_height``
    - receiver: ``h_rx = target_ground + flight_height``
    - LOS with effective-earth bulge:
      ``h_los(f) = h_tx + f*(h_rx-h_tx) - d1*d2/(2 a_e)``
    - obstacle top at sample: ``terrain_sample + building_height + estimated_buffer``
    - Fresnel-Kirchhoff parameter and ITU-R single knife-edge loss

    The path retains the maximum sample loss.  This is a dominant-obstacle
    engineering envelope, not Epstein-Peterson multi-edge combination and not
    a multipath ray tracer.  Do not stack this loss with
    ``building_obstruction_loss_db`` on the same link.
    """
    target = _validate_points(points)
    stations = _validate_points(station_coordinates)
    values = np.asarray(building_features, dtype=float)
    lon_axis = np.asarray(axes[0], dtype=float)
    lat_axis = np.asarray(axes[1], dtype=float)
    rows, cols = len(lat_axis), len(lon_axis)
    if (
        values.ndim != 2
        or values.shape[0] != rows * cols
        or values.shape[1] < 5
        or lon_axis.ndim != 1
        or lat_axis.ndim != 1
        or not len(lon_axis)
        or not len(lat_axis)
    ):
        raise ValueError("building_features must be [len(lat_axis)*len(lon_axis), >=5]")
    if frequency_mhz <= 0 or flight_height_m <= 0:
        raise ValueError("frequency and flight height must be positive")
    if (
        max_height_scale_m <= 0
        or max_loss_db < 0
        or samples_per_km <= 0
        or max_path_distance_km <= 0
        or effective_earth_radius_factor <= 0
        or estimated_height_buffer_m < 0
    ):
        raise ValueError("invalid knife-edge model parameters")
    station_heights = np.asarray(station_height_m, dtype=float)
    if station_heights.ndim == 0:
        station_heights = np.full(len(stations), float(station_heights))
    if station_heights.shape != (len(stations),) or not np.isfinite(station_heights).all():
        raise ValueError("station_height_m must be scalar or one value per station")

    # Normalized maximum height uses height/(2*scale), matching the feature
    # construction in build_overture_building_features.
    max_height = np.clip(values[:, 2], 0.0, 1.0) * (2.0 * max_height_scale_m)
    estimated = np.clip(values[:, 4], 0.0, 1.0)
    terrain = (
        np.zeros(rows * cols, dtype=float)
        if terrain_elevation_m is None
        else np.asarray(terrain_elevation_m, dtype=float)
    )
    if terrain.shape != (rows * cols,) or not np.isfinite(terrain).all():
        raise ValueError("terrain_elevation_m must be finite and aligned with the raster")
    station_ground = np.asarray(station_ground_elevation_m, dtype=float)
    if station_ground.ndim == 0:
        station_ground = np.full(len(stations), float(station_ground))
    if station_ground.shape != (len(stations),) or not np.isfinite(station_ground).all():
        raise ValueError("station_ground_elevation_m must be scalar or one value per station")
    wavelength_m = 299_792_458.0 / (frequency_mhz * 1e6)
    earth_radius_m = 6_371_000.0 * effective_earth_radius_factor

    axis_steps = {
        "lon": float(np.median(np.diff(lon_axis))) if len(lon_axis) > 1 else None,
        "lat": float(np.median(np.diff(lat_axis))) if len(lat_axis) > 1 else None,
    }

    def grid_index(value: float, axis: np.ndarray, key: str) -> int | None:
        step = axis_steps[key]
        if step is None:
            return _grid_index(value, axis)
        index = int(round((value - float(axis[0])) / step))
        if index < 0 or index >= len(axis):
            return None
        if abs(float(axis[index]) - value) > 0.51 * abs(step):
            return None
        return index

    if target_ground_elevation_m is None:
        target_ground = np.zeros(len(target), dtype=float)
        for point_index, (lon, lat) in enumerate(target):
            x = grid_index(float(lon), lon_axis, "lon")
            y = grid_index(float(lat), lat_axis, "lat")
            if x is not None and y is not None:
                target_ground[point_index] = terrain[y * cols + x]
    else:
        target_ground = np.asarray(target_ground_elevation_m, dtype=float)
        if target_ground.ndim == 0:
            target_ground = np.full(len(target), float(target_ground))
        if target_ground.shape != (len(target),) or not np.isfinite(target_ground).all():
            raise ValueError("target_ground_elevation_m must be scalar or one value per point")

    result = np.zeros((len(target), len(stations)), dtype=np.float32)
    for point_index, (lon, lat) in enumerate(target):
        h_rx = float(target_ground[point_index] + flight_height_m)
        for station_index, (station_lon, station_lat) in enumerate(stations):
            dx_km = (lon - station_lon) * 111.32 * np.cos(
                np.radians((lat + station_lat) / 2.0)
            )
            dy_km = (lat - station_lat) * 111.32
            distance_km = float(np.hypot(dx_km, dy_km))
            if distance_km > max_path_distance_km or distance_km < 1e-6:
                continue
            h_tx = float(station_ground[station_index] + station_heights[station_index])
            count = max(3, int(np.ceil(distance_km * samples_per_km)) + 1)
            # Endpoints do not represent intervening buildings.
            fractions = np.linspace(0.0, 1.0, count)[1:-1]
            max_loss = 0.0
            for fraction in fractions:
                sample_lon = station_lon + fraction * (lon - station_lon)
                sample_lat = station_lat + fraction * (lat - station_lat)
                x = grid_index(sample_lon, lon_axis, "lon")
                y = grid_index(sample_lat, lat_axis, "lat")
                if x is None or y is None:
                    continue
                flat = y * cols + x
                d1_m = max(1.0, fraction * distance_km * 1000.0)
                d2_m = max(1.0, (1.0 - fraction) * distance_km * 1000.0)
                curvature_drop_m = d1_m * d2_m / (2.0 * earth_radius_m)
                h_los = h_tx + fraction * (h_rx - h_tx) - curvature_drop_m
                h_obs = (
                    terrain[flat]
                    + max_height[flat]
                    + estimated[flat] * estimated_height_buffer_m
                )
                excess_m = h_obs - h_los
                v = excess_m * np.sqrt(
                    2.0 * (d1_m + d2_m) / (wavelength_m * d1_m * d2_m)
                )
                max_loss = max(max_loss, float(knife_edge_diffraction_loss_db(v)))
            result[point_index, station_index] = min(max_loss, max_loss_db)
    return result
